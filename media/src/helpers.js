const ZONE = 'America/New_York';

function toDate(value) {
    if (value === null || value === undefined || value === '') {
        return null;
    }
    const d = value instanceof Date ? value : new Date(typeof value === 'string' && /^\d+$/.test(value) ? Number(value) : value);
    return Number.isNaN(d.getTime()) ? null : d;
}

function fmtDate(value) {
    const d = toDate(value);
    return d ? d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: ZONE }) : '-';
}

function fmtDateTime(value) {
    const d = toDate(value);
    return d ? d.toLocaleString('en-US', { month: 'short', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit', timeZone: ZONE, timeZoneName: 'short' }) : '-';
}

function timeAgo(value) {
    const d = toDate(value);
    if (!d) {
        return '-';
    }
    const s = Math.round((Date.now() - d.getTime()) / 1000);
    const future = s < 0;
    const a = Math.abs(s);
    const units = [[31536000, 'year'], [2592000, 'month'], [86400, 'day'], [3600, 'hour'], [60, 'minute']];
    for (const [secs, label] of units) {
        if (a >= secs) {
            const n = Math.floor(a / secs);
            return future ? `in ${n} ${label}${n === 1 ? '' : 's'}` : `${n} ${label}${n === 1 ? '' : 's'} ago`;
        }
    }
    return future ? 'in a moment' : 'just now';
}

function duration(ms) {
    const m = Math.max(0, Math.floor(Number(ms) / 60000));
    const d = Math.floor(m / 1440);
    const h = Math.floor((m % 1440) / 60);
    const min = m % 60;
    if (d > 0) {
        return `${d}d ${h}h`;
    }
    if (h > 0) {
        return `${h}h ${min}m`;
    }
    return `${min}m`;
}

